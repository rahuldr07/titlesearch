/**
 * WHERE `✕ Not our party` IS OFFERED AT ALL — rulebook R13, in ONE place.
 *
 * A judgment hit against a different M. Quenby is not a wrong value and not a
 * question: it is a row that must not ship. Everywhere else, suppression is
 * the wrong instrument — correcting a mortgage lender by excluding the field
 * deletes the row instead of fixing it, and an excluded row is GONE
 * (`conflicts.md` C18), with only the typed reason left as evidence that a
 * person decided rather than the pipeline missing it.
 *
 * THE BUTTON AND THE CHORD READ THIS SAME FUNCTION. They used to hold two
 * copies of the rule — `DecisionColumn` gated the button on the path while
 * `useReviewKeys` bound `x` unconditionally — so on `owner.zip` the button was
 * correctly absent and `x` opened the editor anyway, and the exclude posted
 * 200. A rulebook gate spelled twice is a rulebook gate enforced once.
 */
export function offersExclude(path: string): boolean {
  return path.startsWith("judgments.");
}
