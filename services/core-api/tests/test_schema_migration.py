def test_an_unreachable_dsn_really_does_fail(
    alembic_config: Callable[[str], Config], monkeypatch: pytest.MonkeyPatch
) -> None:
    """The control for the three precedence tests below.

    Each of those points the LOSING sources at `UNREACHABLE_DSN` and asserts the
    command succeeds. That proves nothing unless the unreachable DSN genuinely
    fails — a typo making it reachable, or an `env.py` that silently fell back to
    something else, would make all three pass while checking no precedence at
    all.

    🔴 THE MESSAGE MUST NAME THIS SERVER, NOT MERELY BE AN `OperationalError`.
    `pytest.raises(OperationalError)` alone says nothing about WHICH server was
    unreachable, and this test is the control for three others — an `env.py` that
    ignored every source and built an engine from some third DSN would fail with
    an `OperationalError` too, and this control would call that proof. libpq puts
    the host and port it actually tried into its own message
    (`connection to server at "127.0.0.1", port 1 failed: …`), so the assertion
    can read them back out. Host and port come from the constants the DSN itself
    is built from, so the two cannot drift apart.
    """
    monkeypatch.setenv(DATABASE_URL_VARIABLE, UNREACHABLE_DSN)
    config = alembic_config(UNREACHABLE_DSN)

    with pytest.raises(OperationalError) as raised:
        command.check(config)

    message = str(raised.value)
    assert UNREACHABLE_HOST in message, (
        f"the failure does not name {UNREACHABLE_HOST}, so it is not evidence that "
        f"THIS DSN is the one that failed: {message}"
    )
    assert f"port {UNREACHABLE_PORT}" in message, (
        f"the failure does not name port {UNREACHABLE_PORT}: {message}"
    )


