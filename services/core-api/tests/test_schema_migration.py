def test_alembic_check_would_notice_a_model_the_database_does_not_have(
    migrated_database: str, alembic_config: Callable[[str], Config], migration_dsn: str
) -> None:
    """The anti-vacuity guard for the test above.

    A `check` that silently did nothing — a broken `target_metadata`, an `env.py`
    that returned before configuring, an exception class that is never raised —
    would leave the test above green forever. So a table is added to
    `Base.metadata` that the database does not have, and `check` must say so.

    `Base.metadata` is process-global, so the table is removed in a `finally`.
    Without that, every later test in this session would see a diff.
    """
    probe = sa.Table(
        "alembic_check_probe", Base.metadata, sa.Column("id", sa.Integer, primary_key=True)
    )
    try:
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(alembic_config(migration_dsn))
    finally:
        Base.metadata.remove(probe)

    # And back to agreeing, proved rather than assumed: the removal above is what
    # every later test in this session depends on.
    command.check(alembic_config(migration_dsn))


# --- `env.py`'s own behaviour ------------------------------------------------
#
# Everything above drives `env.py` down its happy path. What follows covers the
# two paths that END in a `raise`, and the three DSN sources it declares.
#
# The offline refusal is the ONE PLACE IN TASK 3 WHERE A SECURITY PROPERTY RESTS
# ON A `raise` RATHER THAN ON THE DATABASE. Everywhere else the `INHERIT FALSE`
# membership does the enforcing: forget `SET ROLE` and PostgreSQL refuses. In
# `--sql` mode there is no connection to refuse anything, so Alembic would
# cheerfully emit seven `CREATE TABLE`s that a DBA executes as themselves,
# producing exactly the LOGIN-role ownership `roles.sql` exists to make
# impossible. CONFIRMED: replacing `run_migrations_offline`'s body with an
# ordinary implementation left the suite at 124 passed. Nothing was testing it.


def test_offline_sql_mode_is_refused(
    alembic_config: Callable[[str], Config], migration_dsn: str
) -> None:
    """`--sql` must refuse, because it cannot `SET ROLE`.

    The refusal names the role, so the operator is told what the generated script
    would have got wrong rather than merely that this is unsupported.

    No database is touched: the refusal happens before any engine is built, which
    is also why this test does not request `migrated_database`.
    """
    with pytest.raises(RuntimeError) as raised:
        command.upgrade(alembic_config(migration_dsn), "head", sql=True)

    message = str(raised.value)
    assert "offline" in message
    assert "titlepipe_owner" in message


def test_a_config_naming_no_database_anywhere_is_refused(
    alembic_config: Callable[[str], Config],
    migration_dsn: str,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """All three sources empty is a configuration error, and says so.

    Alembic's own behaviour for a missing URL is to build an engine from the
    empty string, which fails somewhere inside SQLAlchemy with a message about a
    driver. The refusal names all three places a DSN can come from, because the
    person reading it is the person who has to supply one.
    """
    monkeypatch.delenv(DATABASE_URL_VARIABLE, raising=False)
    config = alembic_config(migration_dsn)
    del config.attributes[ALEMBIC_DSN_ATTRIBUTE]

    with pytest.raises(RuntimeError) as raised:
        command.upgrade(config, "head")

    message = str(raised.value)
    assert DATABASE_URL_VARIABLE in message
    assert "alembic.ini" in message
    assert ALEMBIC_DSN_ATTRIBUTE in message


