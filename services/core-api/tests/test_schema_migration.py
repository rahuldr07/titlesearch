def test_a_failed_upgrade_leaves_no_partial_schema_behind(
    migrated_database: str,
    alembic_config: Callable[[str], Config],
    migration_dsn: str,
    alembic_version_table: str,
    tmp_path: Path,
) -> None:
    """🔴 THE WHOLE UPGRADE IS ONE TRANSACTION, ASSERTED RATHER THAN COMMENTED.

    `alembic.ini` used to merely claim `transaction_per_migration` was left at
    its default. A claim in a comment is not a control, and this is the property
    it was claiming: a chain of revisions applied by one `upgrade` either all
    land or none do.

    Proved with a `0002` that creates a table and then executes nonsense. If the
    chain were per-migration, `0001`'s seven tables would survive the failure and
    the assertion below would find them. Because it is one transaction, `public`
    comes back with nothing but Alembic's own version table.

    This also demonstrates the case `migrated_database`'s teardown was restructured
    for: an upgrade that fails part way now still gets a teardown, because the
    `command.upgrade` call lives inside the fixture's `try`.

    The probe revision is written to a `tmp_path` and reached through
    `version_locations`, so nothing is ever created in `migrations/versions/` and
    a crash here cannot leave a stray revision behind for the next run.
    """
    (tmp_path / "0002_probe.py").write_text(_FAILING_REVISION, encoding="utf-8")

    real_config = alembic_config(migration_dsn)
    versions = Path(str(real_config.get_main_option("script_location"))) / "versions"

    probe_config = alembic_config(migration_dsn)
    # `path_separator`, not the older `version_path_separator` — alembic 1.18.5
    # emits a `DeprecationWarning` for the latter, and this suite runs with
    # `-W` defaults where a warning is noise that trains people to ignore
    # warnings.
    probe_config.set_main_option("path_separator", "os")
    probe_config.set_main_option("version_locations", f"{versions}{os.pathsep}{tmp_path}")

    command.downgrade(real_config, "base")
    try:
        with pytest.raises(DBAPIError):
            command.upgrade(probe_config, "head")

        engine = create_engine(migrated_database)
        try:
            with engine.connect() as connection:
                surviving = _public_schema_objects(connection)
        finally:
            engine.dispose()

        assert surviving["relations"] <= {f"r:{alembic_version_table}"}, (
            "a failed upgrade left objects behind, so the revisions are NOT "
            f"running in one transaction: {sorted(surviving['relations'])}"
        )
        assert surviving["functions"] == set()
        assert surviving["enum_types"] == set()
    finally:
        # Back to head for the rest of the module, and for the fixture's own
        # teardown, which downgrades from wherever this left things.
        command.upgrade(real_config, "head")


