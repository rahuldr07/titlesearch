def _tables(connection: Connection) -> set[str]:
    """Ordinary tables in `public`. Views, sequences and indexes are not tables."""
    result = connection.execute(
        text(
            "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = 'public' AND c.relkind = 'r'"
        )
    )
    return {str(row[0]) for row in result}


def _table_owners(connection: Connection) -> dict[str, tuple[str, bool]]:
    """table -> (owner role, whether that role can log in).

    `pg_roles` rather than `pg_authid` for `rolcanlogin`: the view carries it and
    is readable without a superuser, so this assertion does not depend on which
    DSN it is handed.
    """
    result = connection.execute(
        text(
            "SELECT c.relname, r.rolname, r.rolcanlogin "
            "FROM pg_class c "
            "JOIN pg_namespace n ON n.oid = c.relnamespace "
            "JOIN pg_roles r ON r.oid = c.relowner "
            "WHERE n.nspname = 'public' AND c.relkind = 'r'"
        )
    )
    return {str(row[0]): (str(row[1]), bool(row[2])) for row in result}


class ColumnFacts(NamedTuple):
    """Type, nullability and server default — the three things a skeleton column is.

    `default` was not read at all until review pointed it out, so six of seven
    tables' defaults were unverified. It is not decoration: Task 6 seeds
    `tenants` without supplying an `id`, so `gen_random_uuid()` is the only thing
    producing one, and a migration that dropped the default would surface there
    as a `NOT NULL` violation in somebody else's task.
    """

    type_name: str
    nullable: bool
    default: str | None


def _columns(connection: Connection) -> dict[str, dict[str, ColumnFacts]]:
    """table -> column -> `ColumnFacts`.

    `udt_name` rather than `data_type`: `data_type` reports `USER-DEFINED` for an
    enum and `ARRAY` for anything array-shaped, so it cannot tell `na_reason`
    from any other user-defined type.
    """
    result = connection.execute(
        text(
            "SELECT table_name, column_name, udt_name, is_nullable, column_default "
            "FROM information_schema.columns WHERE table_schema = 'public'"
        )
    )
    columns: dict[str, dict[str, ColumnFacts]] = {}
    for row in result:
        columns.setdefault(str(row[0]), {})[str(row[1])] = ColumnFacts(
            str(row[2]), str(row[3]) == "YES", None if row[4] is None else str(row[4])
        )
    return columns


class PrimaryKeyFacts(NamedTuple):
    """The constraint's name, and its key columns IN KEY ORDER.

    A `tuple` and not a `frozenset`, deliberately. `(tenant_id, id)` and
    `(id, tenant_id)` are the same set and different keys: only the first
    tenant-prefixes the backing index, and only the first is what
    `_tenant_primary_key` measured. A set comparison would pass with the prefix
    reversed.
    """

    name: str
    columns: tuple[str, ...]


def _primary_keys(connection: Connection) -> dict[str, PrimaryKeyFacts]:
    """table -> `PrimaryKeyFacts`, read from `pg_constraint`.

    `pg_constraint.conkey` is a `smallint[]` of attribute numbers IN KEY ORDER,
    and `pg_attribute` is keyed on `(attrelid, attnum)` — so the join has to
    carry the ordinal through `WITH ORDINALITY` and aggregate on it. Joining on
    `a.attnum = ANY(c.conkey)` instead would return the columns in whatever order
    the planner produced them, which is exactly the assertion this exists to
    make.

    A table with no primary key contributes no row, so it is simply absent from
    the mapping — which is why the caller asserts the KEY SET as well as the
    values.
    """
    result = connection.execute(
        text(
            "SELECT c.conrelid::regclass::text, c.conname, "
            "       array_agg(a.attname ORDER BY k.ord) "
            "FROM pg_constraint c "
            "JOIN LATERAL unnest(c.conkey) WITH ORDINALITY AS k(attnum, ord) ON true "
            "JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.attnum "
            "WHERE c.contype = 'p' AND c.connamespace = 'public'::regnamespace "
            "GROUP BY 1, 2"
        )
    )
    return {
        str(row[0]): PrimaryKeyFacts(str(row[1]), tuple(str(column) for column in row[2]))
        for row in result
    }


def _public_schema_objects(connection: Connection, version_table: str) -> dict[str, set[str]]:
    """Everything in `public` that a migration could have created and left behind.

    Broader than the table set on purpose. The round trip used to diff tables and
    `pg_enum` only, so a downgrade that leaked a FUNCTION, a SEQUENCE, a VIEW or
    a standalone INDEX was invisible to it — and `0001` creates a function, which
    is exactly one of the blind spots.

    Indexes belonging to `alembic_version` are excluded: that table survives
    `downgrade base` by design, so its primary-key index does too, and its name
    is Alembic's to choose rather than ours to hardcode.

    `version_table` is a PARAMETER rather than the literal `"alembic_version"`
    this function used to carry. Four tests in this file already take the
    `alembic_version_table` fixture and then called a helper that ignored it, so
    the name existed in two places and only one of them was the seam.
    """
    relations = connection.execute(
        text(
            "SELECT c.relkind, c.relname FROM pg_class c "
            "JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = 'public' AND c.relkind IN ('r', 'S', 'v', 'm', 'p', 'f')"
        )
    )
    indexes = connection.execute(
        text(
            "SELECT indexname FROM pg_indexes "
            "WHERE schemaname = 'public' AND tablename <> :version_table"
        ),
        {"version_table": version_table},
    )
    functions = connection.execute(
        text(
            "SELECT p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace "
            "WHERE n.nspname = 'public'"
        )
    )
    enum_types = connection.execute(
        text(
            "SELECT t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace "
            "WHERE n.nspname = 'public' AND t.typtype = 'e'"
        )
    )
    return {
        "relations": {f"{row[0]}:{row[1]}" for row in relations},
        "indexes": {str(row[0]) for row in indexes},
        "functions": {str(row[0]) for row in functions},
        "enum_types": {str(row[0]) for row in enum_types},
    }


def _enum_labels(connection: Connection, type_name: str) -> tuple[str, ...]:
    """The type's labels in `enumsortorder`, or `()` when the type does not exist.

    `ORDER BY e.enumsortorder` is the server's own ordering, which is what a
    comparison, a `<` and a `MIN()` over the type would use. Reading the rows
    unordered and sorting them here would make the order assertion vacuous.
    """
    result = connection.execute(
        text(
            "SELECT e.enumlabel FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid "
            "WHERE t.typname = :type_name ORDER BY e.enumsortorder"
        ),
        {"type_name": type_name},
    )
    return tuple(str(row[0]) for row in result)


class TriggerFacts(NamedTuple):
    """What has to be true of an append-only trigger for it to be one.

    All three, because each can be broken without touching the others, and
    breaking any one of them switches the protection off:

    * `is_statement_level` — `tgtype & 1` is `TRIGGER_TYPE_ROW`. A row trigger
      does not fire when a statement matches nothing, which is exactly the case
      under Task 4's RLS;
    * `is_before` — `tgtype & 2` is `TRIGGER_TYPE_BEFORE`. `0001` calls this
      load-bearing ("so nothing is written before the refusal") and until now
      nothing asserted it;
    * `enabled` — `tgenabled`, which was NOT being read at all. MEASURED
      2026-08-05: `titlepipe_migration` with `SET ROLE titlepipe_owner` can issue
      `ALTER TABLE audit_log DISABLE TRIGGER ALL`, after which `tgenabled` is
      `'D'` and **`tgtype` is unchanged** — so a check on `tgtype` alone passes
      with the trigger switched off. `'O'` is "fires in origin/local
      replication role", which is the ordinary enabled state.
    """

    is_statement_level: bool
    is_before: bool
    enabled: str


def _triggers(connection: Connection, table: str) -> dict[str, TriggerFacts]:
    """trigger name -> the three facts above.

    `tgisinternal` triggers are the ones PostgreSQL creates for constraints; they
    are not ours and would make an exact-set assertion impossible to write.
    """
    result = connection.execute(
        text(
            "SELECT t.tgname, (t.tgtype & 1) = 0, (t.tgtype & 2) <> 0, t.tgenabled "
            "FROM pg_trigger t "
            "JOIN pg_class c ON c.oid = t.tgrelid "
            "WHERE c.relname = :table AND NOT t.tgisinternal"
        ),
        {"table": table},
    )
    return {str(row[0]): TriggerFacts(bool(row[1]), bool(row[2]), str(row[3])) for row in result}


def _sqlstate(error: DBAPIError) -> str | None:
    """The five-character SQLSTATE psycopg attached, if it attached one.

    Checked with `isinstance` rather than trusted: `getattr` on a DBAPI exception
    returns whatever is there, and a test that compared `Any` to a string would
    pass for a `None` as readily as for a code.
    """
    sqlstate = getattr(error.orig, "sqlstate", None)
    return sqlstate if isinstance(sqlstate, str) else None


def test_the_first_revision_id_is_the_literal_0001(alembic_config: Callable[[str], Config]) -> None:
    """Task 4's `0002` sets `down_revision = "0001"`, so the id is a contract.

    Alembic's default is a random hash. A hash would work exactly as well for
    Alembic and not at all for the person writing `0002`, who would have to look
    it up and would have nothing to notice if they looked up the wrong one.

    🔴 THIS ASSERTS THE IDENTITY OF `0001`, NOT THE HEAD OF THE CHAIN, AND THE
    DIFFERENCE IS THE ENTIRE VALUE OF THE TEST. It used to read
    `scripts.get_current_head() == FIRST_REVISION`, which is the head of the
    whole chain — so the moment Task 4 lands `0002`, this Task 3 test goes red
    with `assert '0002' == '0001'`. MEASURED with a `0002` stub. A test written
    to give Task 4's author a literal to read would instead have handed them a
    failure in somebody else's file, naming the head and saying nothing about
    `0001`, and left them to work out whether their own revision id was wrong.

    `get_base()` is the assertion that stays true forever: `0001` is the base of
    the chain however many revisions follow it. `down_revision is None` is the
    same claim read off the script itself, and both survive `0002`, `0003` and
    everything after.

    The DSN is irrelevant here — this reads the script directory, not a database
    — so a placeholder is passed rather than a fixture requested, which keeps
    this test off the container entirely.
    """
    scripts = ScriptDirectory.from_config(alembic_config("postgresql+psycopg://unused/unused"))

    revision = scripts.get_revision(FIRST_REVISION)
    assert revision.revision == FIRST_REVISION
    assert revision.down_revision is None, "0001 must be the base revision"
    assert scripts.get_base() == FIRST_REVISION, (
        "0001 must remain the base of the chain; a later revision may follow it "
        "but nothing may precede it"
    )


