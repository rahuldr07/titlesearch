def test_audit_log_refuses_an_update_that_matches_no_rows(
    migrated_database: str, seam_engine: Callable[[str], Engine]
) -> None:
    """🔴 THE ZERO-MATCH UPDATE. This is the whole reason the trigger is STATEMENT.

    `FOR EACH ROW` fires once per affected row, so it does not fire at all when a
    statement affects none — and under Task 4's `FORCE ROW LEVEL SECURITY` a
    cross-tenant `UPDATE` matches exactly zero rows. A row-level trigger would
    therefore be SILENT for the case this trigger exists to refuse, and an
    append-only proof written with a MATCHING update would pass while proving
    nothing about the choice.

    The id is a fresh `gen_random_uuid()`, so it matches nothing by construction
    rather than by the table happening to be empty.

    THE SQLSTATE IS ASSERTED, NOT MERELY THAT SOMETHING RAISED. A misspelled
    column in this very test raises too — `42703` — and would otherwise pass as
    proof that the trigger works.
    """
    engine = seam_engine(migrated_database)
    try:
        with engine.connect() as connection:
            absent = connection.execute(text("SELECT gen_random_uuid()")).scalar_one()
            with pytest.raises(DBAPIError) as raised:
                connection.execute(
                    text("UPDATE audit_log SET tenant_id = tenant_id WHERE id = :id"),
                    {"id": absent},
                )
            connection.rollback()
    finally:
        engine.dispose()

    assert _sqlstate(raised.value) == APPEND_ONLY_SQLSTATE, (
        f"expected SQLSTATE {APPEND_ONLY_SQLSTATE} from the append-only trigger, "
        f"got {_sqlstate(raised.value)}: {raised.value}"
    )


def test_audit_log_refuses_an_update_that_matches_a_row(
    migrated_database: str, seam_engine: Callable[[str], Engine]
) -> None:
    """The control. This stays green whether the trigger is STATEMENT or ROW.

    That is exactly why it cannot be the proof, and why it is worth keeping
    beside the zero-match test: the two together say that the append-only rule
    holds in both cases, and the zero-match one alone says the trigger is
    statement-level.

    The row is inserted and the whole thing rolled back, so `audit_log` is empty
    again for the next test.
    """
    engine = seam_engine(migrated_database)
    try:
        with engine.connect() as connection:
            row_id = connection.execute(
                text("INSERT INTO audit_log (tenant_id) VALUES (gen_random_uuid()) RETURNING id")
            ).scalar_one()

            with pytest.raises(DBAPIError) as raised:
                connection.execute(
                    text("UPDATE audit_log SET tenant_id = tenant_id WHERE id = :id"),
                    {"id": row_id},
                )
            connection.rollback()
    finally:
        engine.dispose()

    assert _sqlstate(raised.value) == APPEND_ONLY_SQLSTATE


def test_audit_log_refuses_delete_and_truncate(
    migrated_database: str, seam_engine: Callable[[str], Engine]
) -> None:
    """Append-only means all three verbs, not just UPDATE.

    `TRUNCATE` needs its own trigger — PostgreSQL rejects a `FOR EACH ROW`
    trigger that names TRUNCATE, so it cannot share one with UPDATE and DELETE
    without making the STATEMENT/ROW decision unrepresentable. Both refusals go
    through the same function and therefore the same SQLSTATE.
    """
    engine = seam_engine(migrated_database)
    try:
        with engine.connect() as connection:
            for statement in ("DELETE FROM audit_log", "TRUNCATE audit_log"):
                with pytest.raises(DBAPIError) as raised:
                    connection.execute(text(statement))
                connection.rollback()
                assert _sqlstate(raised.value) == APPEND_ONLY_SQLSTATE, statement
    finally:
        engine.dispose()


def test_upgrade_downgrade_upgrade_is_clean(
    migrated_database: str,
    alembic_config: Callable[[str], Config],
    migration_dsn: str,
    alembic_version_table: str,
    seam_engine: Callable[[str], Engine],
) -> None:
    """🔴 THE ROUND TRIP. `migrated_database` already ran the first upgrade.

    A `downgrade` that misses an object is invisible on a fresh database: the
    first `upgrade` works, and only the SECOND one — after a downgrade — finds
    the leftover, as `already exists`. The likeliest such leftover is the ENUM,
    because **`DROP TABLE` does not drop a type**.

    WHAT IS DIFFED IS THE WHOLE `public` SCHEMA, not the table set. This used to
    compare tables and `pg_enum` only, which is blind to a leaked FUNCTION,
    SEQUENCE, VIEW or standalone INDEX — and `0001` creates a function, so one of
    those blind spots was directly in front of it. `_public_schema_objects` is
    the diff, and `alembic_version` plus its own index is the only permitted
    residue: Alembic creates that table outside every revision script and
    `downgrade base` empties rather than drops it. `migrated_database`'s teardown
    removes it by hand for exactly that reason.

    WHY THE POST-DOWNGRADE STATE IS CAPTURED HERE AND ASSERTED LATER. Asserting
    it immediately would be the stronger-reading test and the weaker diagnostic:
    it would fire before the second `upgrade` ever ran, so the failure would be
    this file's assertion message rather than PostgreSQL's own `type "na_reason"
    already exists` — the message that says which object was left behind and is
    the thing a reader can act on. The second `upgrade` is therefore allowed to
    hit the leftover first, and the capture below is the independent check that
    survives if a future downgrade leaves something the re-upgrade happens not to
    collide with.
    """
    config = alembic_config(migration_dsn)

    command.downgrade(config, "base")

    engine = seam_engine(migrated_database)
    try:
        with engine.connect() as connection:
            after_downgrade = _public_schema_objects(connection, alembic_version_table)

        command.upgrade(config, "head")

        with engine.connect() as connection:
            assert _tables(connection) == SKELETON_TABLES | {alembic_version_table}
            assert _enum_labels(connection, NA_REASON_TYPE_NAME) == NA_REASON_LABELS
    finally:
        engine.dispose()

    assert after_downgrade == {
        "relations": {f"r:{alembic_version_table}"},
        "indexes": set(),
        "functions": set(),
        "enum_types": set(),
    }, (
        "downgrade did not return `public` to empty. Everything below `relations: "
        f"['r:{alembic_version_table}']` is a leak: {after_downgrade}"
    )


