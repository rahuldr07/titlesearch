def test_every_table_is_owned_by_the_owner_and_no_login_role_owns_one(
    migrated_database: str, owner_role: str, alembic_version_table: str
) -> None:
    """🔴 THE PROOF TASK 2 COULD NOT WRITE, because no table existed then.

    A table's owner BYPASSES row-level security on it unless the table is
    `FORCE ROW LEVEL SECURITY`. Task 4 will set `FORCE`, and this is the
    assertion that means Task 4 does not have to be the only thing standing
    between a LOGIN role and every tenant's rows: ownership sits on
    `titlepipe_owner`, which nothing can authenticate as.

    TWO ASSERTIONS, AND THE SECOND IS NOT IMPLIED BY THE FIRST. The first names
    the role this repository chose. The second states the PROPERTY that made it
    the right choice, and it would still catch a future migration that moved
    ownership to some new non-login role while `owner_role` was updated to
    match — and, more usefully, one that moved it to `titlepipe_migration`,
    which is the mistake a forgotten `SET ROLE` in `env.py` actually produces.

    The table set is asserted first. Both claims below are `for` loops, and a
    `for` over nothing passes.
    """
    engine = create_engine(migrated_database)
    try:
        with engine.connect() as connection:
            owners = _table_owners(connection)
    finally:
        engine.dispose()

    assert set(owners) == SKELETON_TABLES | {alembic_version_table}

    for table, (owner, can_log_in) in sorted(owners.items()):
        assert owner == owner_role, f"{table} is owned by {owner}, not {owner_role}"
        assert can_log_in is False, (
            f"{table} is owned by {owner}, which can LOG IN. A table's owner "
            f"bypasses RLS unless FORCE is set, so this is a live bypass."
        )


def test_every_tenant_table_carries_its_own_tenant_id_and_the_registry_does_not(
    migrated_database: str,
) -> None:
    """The column contract, per table, as an exact set.

    `tenant_id uuid NOT NULL` on the six is what lets Task 4's policy be
    `tenant_id = …` with no join. `NOT NULL` is asserted because `NULL = <uuid>`
    is NULL rather than true: a nullable column would allow rows no tenant can
    read, none can delete, and no isolation test can see.
    """
    engine = create_engine(migrated_database)
    try:
        with engine.connect() as connection:
            columns = _columns(connection)
    finally:
        engine.dispose()

    for table, expected in sorted(EXPECTED_COLUMNS.items()):
        assert set(columns[table]) == set(expected), f"{table} has the wrong columns"
        assert columns[table]["id"] == ColumnFacts("uuid", False, UUID_DEFAULT)
        assert columns[table]["created_at"] == ColumnFacts("timestamptz", False, NOW_DEFAULT)

    for table in sorted(EXPECTED_COLUMNS.keys() - {"tenants"}):
        assert columns[table]["tenant_id"] == ColumnFacts("uuid", False, None), (
            f"{table}.tenant_id must be uuid NOT NULL; every RLS policy keys on it"
        )

    assert "tenant_id" not in columns["tenants"], (
        "tenants is the registry: its primary key IS the tenant id, and Task 4 "
        "derives the tenant tables from the presence of a tenant_id column"
    )

    # 🔴 NULLABLE, AND THE NULLABILITY IS THE POINT. An engine with no coordinate
    # support declares `null` and never fabricates a box; Reader A is a VLM and
    # genuinely cannot cite one.
    assert columns["field_readings"]["line_coords"] == ColumnFacts("jsonb", True, None)
    # NULL when the field has a value. This is NOT a third NA state — the two NA
    # states are labels of the enum below.
    assert columns["fields"]["na_reason"] == ColumnFacts("na_reason", True, None)


def test_na_reason_has_exactly_four_labels_in_exactly_this_order(
    migrated_database: str,
) -> None:
    """COUNT AND ORDER, ASSERTED SEPARATELY, because they fail separately.

    Adding a fifth label changes the count and leaves the first four in order; a
    tuple comparison alone would report that as an order failure and send the
    reader looking for a reordering that did not happen. Swapping two labels
    leaves the count untouched, so a count alone would not see it at all.

    The expected labels come from `titlepipe_core.db.models`, and the migration
    that created the type repeats them as its own literal — deliberately, since a
    migration is a frozen snapshot. This comparison is the only thing keeping the
    two copies in agreement.

    Order matters to PostgreSQL, not only to us: `enumsortorder` is what `<`,
    `ORDER BY` and `MIN()` on this type use.
    """
    engine = create_engine(migrated_database)
    try:
        with engine.connect() as connection:
            labels = _enum_labels(connection, "na_reason")
    finally:
        engine.dispose()

    assert len(labels) == len(NA_REASON_LABELS), (
        f"na_reason has {len(labels)} labels, expected {len(NA_REASON_LABELS)}: {labels}"
    )
    assert labels == NA_REASON_LABELS, f"na_reason labels are out of order: {labels}"


def test_audit_logs_triggers_are_statement_level_before_and_enabled(
    migrated_database: str,
) -> None:
    """The STATEMENT/ROW/BEFORE/enabled facts, read from the catalog.

    The behavioural tests below are the primary proof and this cannot replace
    them — a trigger that is statement-level, `BEFORE` and enabled but raises
    nothing would satisfy every assertion here and refuse no writes. What this
    adds is DIAGNOSIS: when an append-only test goes red, this says which of the
    four ways it broke.

    That is precisely why `tgenabled` is read. Without it this test could not
    tell "re-declared `FOR EACH ROW`" from "still statement-level, switched off"
    — and `ALTER TABLE audit_log DISABLE TRIGGER ALL` leaves `tgtype` untouched,
    so the old version of this test PASSED with the trigger disabled. A
    diagnostic that is blind to one of the failure modes it exists to
    distinguish is not doing its job.
    """
    engine = create_engine(migrated_database)
    try:
        with engine.connect() as connection:
            triggers = _triggers(connection, "audit_log")
    finally:
        engine.dispose()

    assert set(triggers) == set(EXPECTED_TRIGGERS)
    for name, facts in sorted(triggers.items()):
        assert facts.is_statement_level is True, (
            f"{name} is FOR EACH ROW. A row trigger does not fire when a "
            f"statement matches no rows, and under Task 4's RLS a cross-tenant "
            f"UPDATE matches exactly zero."
        )
        assert facts.is_before is True, (
            f"{name} is an AFTER trigger. The refusal must land before anything is written."
        )
        assert facts.enabled == TRIGGER_ENABLED, (
            f"{name} has tgenabled={facts.enabled!r}, not {TRIGGER_ENABLED!r}. "
            f"A disabled trigger keeps its tgtype and refuses nothing."
        )


def test_audit_log_refuses_an_update_that_matches_no_rows(migrated_database: str) -> None:
    """🔴 THE ZERO-MATCH UPDATE. This is the whole reason the trigger is STATEMENT.

    `FOR EACH ROW` fires once per affected row, so it does not fire at all when a
    statement affects none — and under Task 4's `FORCE ROW LEVEL SECURITY` a
    cross-tenant `UPDATE` matches exactly zero rows. A row-level trigger would
    therefore be SILENT for the case this trigger exists to refuse, and an
    append-only proof written with a MATCHING update would pass while proving
    nothing about the choice.

    The id is a fresh `gen_random_uuid()`, so it matches nothing by construction
    rather than by the table happening to be empty.

    THE SQLSTATE IS ASSERTED, NOT MERELY THAT SOMETHING RAISED. A misspelled
    column in this very test raises too — `42703` — and would otherwise pass as
    proof that the trigger works.
    """
    engine = create_engine(migrated_database)
    try:
        with engine.connect() as connection:
            absent = connection.execute(text("SELECT gen_random_uuid()")).scalar_one()
            with pytest.raises(DBAPIError) as raised:
                connection.execute(
                    text("UPDATE audit_log SET tenant_id = tenant_id WHERE id = :id"),
                    {"id": absent},
                )
            connection.rollback()
    finally:
        engine.dispose()

    assert _sqlstate(raised.value) == APPEND_ONLY_SQLSTATE, (
        f"expected SQLSTATE {APPEND_ONLY_SQLSTATE} from the append-only trigger, "
        f"got {_sqlstate(raised.value)}: {raised.value}"
    )


def test_audit_log_refuses_an_update_that_matches_a_row(migrated_database: str) -> None:
    """The control. This stays green whether the trigger is STATEMENT or ROW.

    That is exactly why it cannot be the proof, and why it is worth keeping
    beside the zero-match test: the two together say that the append-only rule
    holds in both cases, and the zero-match one alone says the trigger is
    statement-level.

    The row is inserted and the whole thing rolled back, so `audit_log` is empty
    again for the next test.
    """
    engine = create_engine(migrated_database)
    try:
        with engine.connect() as connection:
            row_id = connection.execute(
                text("INSERT INTO audit_log (tenant_id) VALUES (gen_random_uuid()) RETURNING id")
            ).scalar_one()

            with pytest.raises(DBAPIError) as raised:
                connection.execute(
                    text("UPDATE audit_log SET tenant_id = tenant_id WHERE id = :id"),
                    {"id": row_id},
                )
            connection.rollback()
    finally:
        engine.dispose()

    assert _sqlstate(raised.value) == APPEND_ONLY_SQLSTATE


def test_audit_log_refuses_delete_and_truncate(migrated_database: str) -> None:
    """Append-only means all three verbs, not just UPDATE.

    `TRUNCATE` needs its own trigger — PostgreSQL rejects a `FOR EACH ROW`
    trigger that names TRUNCATE, so it cannot share one with UPDATE and DELETE
    without making the STATEMENT/ROW decision unrepresentable. Both refusals go
    through the same function and therefore the same SQLSTATE.
    """
    engine = create_engine(migrated_database)
    try:
        with engine.connect() as connection:
            for statement in ("DELETE FROM audit_log", "TRUNCATE audit_log"):
                with pytest.raises(DBAPIError) as raised:
                    connection.execute(text(statement))
                connection.rollback()
                assert _sqlstate(raised.value) == APPEND_ONLY_SQLSTATE, statement
    finally:
        engine.dispose()


def test_upgrade_downgrade_upgrade_is_clean(
    migrated_database: str,
    alembic_config: Callable[[str], Config],
    migration_dsn: str,
    alembic_version_table: str,
) -> None:
    """🔴 THE ROUND TRIP. `migrated_database` already ran the first upgrade.

    A `downgrade` that misses an object is invisible on a fresh database: the
    first `upgrade` works, and only the SECOND one — after a downgrade — finds
    the leftover, as `already exists`. The likeliest such leftover is the ENUM,
    because **`DROP TABLE` does not drop a type**.

    WHAT IS DIFFED IS THE WHOLE `public` SCHEMA, not the table set. This used to
    compare tables and `pg_enum` only, which is blind to a leaked FUNCTION,
    SEQUENCE, VIEW or standalone INDEX — and `0001` creates a function, so one of
    those blind spots was directly in front of it. `_public_schema_objects` is
    the diff, and `alembic_version` plus its own index is the only permitted
    residue: Alembic creates that table outside every revision script and
    `downgrade base` empties rather than drops it. `migrated_database`'s teardown
    removes it by hand for exactly that reason.

    WHY THE POST-DOWNGRADE STATE IS CAPTURED HERE AND ASSERTED LATER. Asserting
    it immediately would be the stronger-reading test and the weaker diagnostic:
    it would fire before the second `upgrade` ever ran, so the failure would be
    this file's assertion message rather than PostgreSQL's own `type "na_reason"
    already exists` — the message that says which object was left behind and is
    the thing a reader can act on. The second `upgrade` is therefore allowed to
    hit the leftover first, and the capture below is the independent check that
    survives if a future downgrade leaves something the re-upgrade happens not to
    collide with.
    """
    config = alembic_config(migration_dsn)

    command.downgrade(config, "base")

    engine = create_engine(migrated_database)
    try:
        with engine.connect() as connection:
            after_downgrade = _public_schema_objects(connection)

        command.upgrade(config, "head")

        with engine.connect() as connection:
            assert _tables(connection) == SKELETON_TABLES | {alembic_version_table}
            assert _enum_labels(connection, "na_reason") == NA_REASON_LABELS
    finally:
        engine.dispose()

    assert after_downgrade == {
        "relations": {f"r:{alembic_version_table}"},
        "indexes": set(),
        "functions": set(),
        "enum_types": set(),
    }, (
        "downgrade did not return `public` to empty. Everything below `relations: "
        f"['r:{alembic_version_table}']` is a leak: {after_downgrade}"
    )


